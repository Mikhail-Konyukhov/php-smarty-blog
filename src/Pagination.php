<?php

declare(strict_types=1);

namespace App;

/**
 * Пагинация одного списка: сколько страниц, сколько статей пропустить до
 * текущей и какие номера страниц показать.
 */
final class Pagination
{
    /** Сколько номеров показывать с каждой стороны от текущей страницы. */
    private const AROUND = 2;

    /** Число страниц, не меньше 1: у пустого списка одна пустая страница. */
    public readonly int $pages;

    /** Сколько статей пропустить до текущей страницы, значение для OFFSET. */
    public readonly int $offset;

    /**
     * @param int $total   сколько всего статей в списке, от 0
     * @param int $page    номер текущей страницы, от 1. Может быть больше
     *                     последней: это проверяет вызывающий код, сравнивая
     *                     его с $pages
     * @param int $perPage сколько статей на странице, от 1
     */
    public function __construct(int $total, private readonly int $page, int $perPage)
    {
    }

    /**
     * Номера страниц для вывода под списком.
     *
     * Всегда есть первая и последняя страница и по AROUND страниц с каждой
     * стороны от текущей. На месте пропуска стоит null, шаблон выводит его
     * как «…». Если пропущена ровно одна страница, вместо «…» стоит её номер:
     * «1 2 3», а не «1 … 3».
     *
     * Пример: 12 страниц, текущая 6 → [1, null, 4, 5, 6, 7, 8, null, 12].
     *
     * @return list<int|null> номера страниц по возрастанию и null на месте
     *                        пропусков; для одной страницы — [1]
     */
    public function links(): array
    {
    }
}
